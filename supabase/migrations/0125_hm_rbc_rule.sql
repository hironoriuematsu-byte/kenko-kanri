-- ============================================================
-- 0125_hm_rbc_rule.sql : 赤血球数の判定基準を追加
-- ============================================================
-- 定期健康診断の貧血検査は「血色素量および赤血球数」(労働安全衛生規則第44条)。
-- 0117 では血色素量のみを登録していたため、赤血球数を追加する。
--
-- 数値は日本人間ドック・予防医療学会の判定区分に沿った値を既定として
-- 登録する。事務所の方針に合わせて「判定基準の設定(A〜D)」の画面から
-- 変更できる。
--
-- 単位は ×10^4/μL(例: 450)。×10^6/μL(例: 4.50)で報告された場合は
-- アプリ側で換算して判定する。
--
-- ※ 0117 を再実行すると判定基準がすべて入れ直されるため、
--    0117 のあとに本ファイルを実行すること。
-- ============================================================

delete from public.hm_judgment_rules where item_key = 'rbc';

insert into public.hm_judgment_rules
  (item_key, item_label, unit, sex, grade, min_value, max_value, match_text, sort_order)
values
  -- 男性: A 400-539 / B 360-399・540-599 / D 359以下・600以上
  ('rbc', '赤血球数', '×10^4/μL', 'male', 'B', 360, 399, null, 1),
  ('rbc', '赤血球数', '×10^4/μL', 'male', 'B', 540, 599, null, 2),
  ('rbc', '赤血球数', '×10^4/μL', 'male', 'D', null, 359, null, 3),
  ('rbc', '赤血球数', '×10^4/μL', 'male', 'D', 600, null, null, 4),
  -- 女性: A 360-489 / B 330-359・490-549 / D 329以下・550以上
  ('rbc', '赤血球数', '×10^4/μL', 'female', 'B', 330, 359, null, 1),
  ('rbc', '赤血球数', '×10^4/μL', 'female', 'B', 490, 549, null, 2),
  ('rbc', '赤血球数', '×10^4/μL', 'female', 'D', null, 329, null, 3),
  ('rbc', '赤血球数', '×10^4/μL', 'female', 'D', 550, null, null, 4);


-- ------------------------------------------------------------
-- 適用状況の確認
-- ------------------------------------------------------------
select item_label as 項目,
       sex as 性別,
       grade as 判定,
       coalesce(min_value::text, '(下限なし)') as 下限,
       coalesce(max_value::text, '(上限なし)') as 上限
  from public.hm_judgment_rules
 where item_key = 'rbc'
 order by sex, sort_order;
